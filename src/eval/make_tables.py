"""Generate the results tables for both manuscripts directly from the artifacts.

No number is typed by hand. Inputs:
  results/external_v1_preregistered  v1, the engine frozen before the SmartBugs run
  results/external_v2                v2, the revised engine's SmartBugs run (kept as archived)
  results/external                   v3, the final engine on SmartBugs, and the baselines
  results/heldout                    SolidiFI held-out run of v2 (frozen before the run) and baselines
  results/solidifi_postfix           SolidiFI run of v3 (post hoc)
  results/ablation                   reentrancy ablation of the final engine
  results/timing                     analysis-stage timing of the final engine

Outputs: paper/rewrite/generated_tables.tex (journal) and paper/rewrite/generated_tables_conference.tex.
"""
import csv
import glob
import json
import os
import sys
from collections import Counter

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
RESULTS = os.path.join(REPO, "results")
PAPER = os.path.join(REPO, "paper")
sys.path.insert(0, os.path.join(REPO, "src"))
sys.path.insert(0, os.path.join(REPO, "src", "eval"))

from engine_options import ABLATIONS  # noqa: E402
from score_external import score_category  # noqa: E402

SMARTBUGS = [("reentrancy", "Reentrancy"), ("denial_of_service", "Denial of service"),
             ("access_control", "Access control"), ("arithmetic", "Arithmetic")]
HELDOUT = [("reentrancy", "Reentrancy"), ("arithmetic", "Arithmetic")]
SWC_CLASSES = [("SWC-107", "SWC-107 (reentrancy)"), ("SWC-101", "SWC-101 (truncation)"),
               ("SWC-128", "SWC-128 (loop gas)"), ("SWC-112", "SWC-112 (delegatecall)"),
               ("SWC-124", "SWC-124 (slot collision)"), ("SWC-114", "SWC-114 (oracle; not scored)")]
ABLATION_LABELS = {
    "full": "Final engine",
    "no_stipend_exclusion": "No stipend exclusion",
    "constant_gas_only": "Constant-gas stipend rule only",
    "no_slot_mutex": "No slot-mutex rule",
    "no_mutex": "No mutex rules",
    "mutex_by_reachability": "Mutex by reachability (no dominance)",
    "no_push0_decode": "No PUSH0 decoding",
    "no_cbor_strip": "No CBOR stripping",
    "pre_fix_v2": "Pre-fix engine (v2)",
}
GENERATED_NOTE = "% Generated by src/eval/make_tables.py from results/. Do not edit by hand.\n"


def load_json(relative: str) -> dict:
    with open(os.path.join(RESULTS, relative), encoding="utf-8") as handle:
        return json.load(handle)


def load_rows(pattern: str) -> list:
    rows = []
    for path in sorted(glob.glob(os.path.join(RESULTS, pattern))):
        with open(path, newline="", encoding="utf-8") as handle:
            rows.extend(csv.DictReader(handle))
    return rows


def pct(value) -> str:
    return "n/a" if value is None else f"{100 * value:.1f}"


def interval(bounds) -> str:
    return "" if bounds is None else f" [{100 * bounds[0]:.1f}, {100 * bounds[1]:.1f}]"


def detection_line(label: str, tool: str, score: dict) -> str:
    return (f"{label} & {tool} & {score['tp']} & {score['fp']} & {score['fn']} & {score['tn']} & "
            f"{pct(score['recall'])}{interval(score['recall_ci95'])} & {pct(score['precision'])} & "
            f"{pct(score['fpr'])}{interval(score['fpr_ci95'])} \\\\")


def smartbugs_tools(include_v2: bool) -> list:
    tools = [("EVM-Guard v1 (pre-registered)", load_json("external_v1_preregistered/evm_guard_scores.json"))]
    if include_v2:
        tools.append(("EVM-Guard v2 (revised)", load_json("external_v2/evm_guard_scores.json")))
    tools += [("EVM-Guard v3 (final)", load_json("external/evm_guard_scores.json")),
              ("Slither 0.11.6", load_json("external/slither_scores.json")),
              ("Mythril 0.24.8", load_json("external/mythril_scores.json"))]
    return tools


def detection_table(categories: list, tools: list, caption: str, label: str, wide: bool) -> str:
    env = "table*" if wide else "table"
    lines = [f"\\begin{{{env}}}[t]", "\\centering", "\\small", f"\\caption{{{caption}}}", f"\\label{{{label}}}",
             "\\resizebox{\\textwidth}{!}{%" if wide else "\\resizebox{\\columnwidth}{!}{%",
             "\\begin{tabular}{@{}llrrrrlrl@{}}", "\\toprule",
             "Category & Tool & TP & FP & FN & TN & Recall (\\%) & Precision (\\%) & FPR (\\%) \\\\", "\\midrule"]
    for index_category, (key, name) in enumerate(categories):
        for index, (tool, data) in enumerate(tools):
            lines.append(detection_line(name if index == 0 else "", tool, data["flagged_any"][key]))
        last = index_category == len(categories) - 1
        lines.append("\\bottomrule" if last else "\\midrule")
    lines += ["\\end{tabular}%", "}", f"\\end{{{env}}}", ""]
    return "\n".join(lines)


def runtime_table() -> str:
    timing = load_json("timing/evm_guard_analysis_timing.json")["average"]
    contracts = load_rows("external/evm_guard_contracts.csv")
    files = load_rows("external/evm_guard_files.csv")
    errors = sum(1 for row in contracts if row["status"] != "ok")
    lines = [
        "\\begin{table}[t]", "\\centering", "\\small",
        "\\caption{Run outcomes and per-file analysis time on SmartBugs-curated. EVM-Guard times cover the analysis of compiled bytecode only (excluding replay), measured on an idle machine. Baseline times include \\texttt{solc} compilation and come from the committed baseline run.}",
        "\\label{tab:runtime}", "\\resizebox{\\columnwidth}{!}{%", "\\begin{tabular}{@{}lrrrrr@{}}", "\\toprule",
        "Tool & Completed & Errors & Timeouts & Median (ms) & Mean $\\pm$ SD (ms) \\\\", "\\midrule",
        f"EVM-Guard v3 & {len(files) - errors} & {errors} & 0 & {timing['median_ms']:.0f} & "
        f"{timing['mean_ms']:.0f} $\\pm$ {timing['sd_ms']:.0f} \\\\",
    ]
    for tool, relative in (("Slither 0.11.6", "external/slither_scores.json"),
                           ("Mythril 0.24.8", "external/mythril_scores.json")):
        data = load_json(relative)
        status = data["status"]
        lat = data["latency_ms_per_file"]
        lines.append(f"{tool} & {status.get('ok', 0)} & {status.get('error', 0)} & {status.get('timeout', 0)} & "
                     f"{lat['median']:.0f} & {lat['mean']:.0f} $\\pm$ {lat['sd']:.0f} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}%", "}", "\\end{table}", ""]
    return "\n".join(lines)


def count_findings(relative: str) -> tuple:
    rows = load_rows(relative)
    found, confirmed = Counter(), Counter()
    for row in rows:
        found.update(s for s in row["finding_swcs"].split(";") if s)
        confirmed.update(s for s in row["confirmed_swcs"].split(";") if s)
    return len(rows), found, confirmed


def replay_counts_table() -> str:
    _, found_v1, conf_v1 = count_findings("external_v1_preregistered/evm_guard_contracts.csv")
    contracts, found_v3, conf_v3 = count_findings("external/evm_guard_contracts.csv")
    lines = [
        "\\begin{table}[t]", "\\centering", "\\small",
        f"\\caption{{Static findings (F) on {contracts} runtime contracts and the number confirmed by sandbox replay (C), for v1 and the final engine v3. The replay criteria of v1 were permissive; v3 uses the state criteria described in the replay section.}}",
        "\\label{tab:replay}", "\\begin{tabular}{@{}lrrrr@{}}", "\\toprule",
        "Class & F (v1) & C (v1) & F (v3) & C (v3) \\\\", "\\midrule",
    ]
    for swc, name in SWC_CLASSES:
        lines.append(f"{name} & {found_v1[swc]} & {conf_v1[swc]} & {found_v3[swc]} & {conf_v3[swc]} \\\\")
    lines += ["\\midrule",
              f"Total & {sum(found_v1.values())} & {sum(conf_v1.values())} & "
              f"{sum(found_v3.values())} & {sum(conf_v3.values())} \\\\",
              "\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    return "\n".join(lines)


def replay_scores_table() -> str:
    v1 = load_json("external_v1_preregistered/evm_guard_scores.json")["replay_confirmed"]
    v3 = load_json("external/evm_guard_scores.json")["replay_confirmed"]
    lines = [
        "\\begin{table}[t]", "\\centering", "\\small",
        "\\caption{File-level scores counting only replay-confirmed findings, for v1 and v3 (exact 95\\% Clopper--Pearson interval for recall).}",
        "\\label{tab:replay_scores}", "\\resizebox{\\columnwidth}{!}{%", "\\begin{tabular}{@{}llrrrrlr@{}}", "\\toprule",
        "Category & Version & TP & FP & FN & TN & Recall (\\%) & Precision (\\%) \\\\", "\\midrule",
    ]
    for index_category, (key, name) in enumerate(SMARTBUGS[:3]):
        for index, (version, data) in enumerate((("v1", v1), ("v3", v3))):
            s = data[key]
            label = name if index == 0 else ""
            lines.append(f"{label} & {version} & {s['tp']} & {s['fp']} & {s['fn']} & {s['tn']} & "
                         f"{pct(s['recall'])}{interval(s['recall_ci95'])} & {pct(s['precision'])} \\\\")
        lines.append("\\midrule" if index_category < 2 else "\\bottomrule")
    lines += ["\\end{tabular}%", "}", "\\end{table}", ""]
    return "\n".join(lines)


def heldout_tools() -> list:
    return [
        ("EVM-Guard v2 (frozen before run)", load_json("heldout/evm_guard_heldout_scores.json")),
        ("EVM-Guard v3 (final, post hoc)", load_json("solidifi_postfix/evm_guard_heldout_scores.json")),
        ("Slither 0.11.6", load_json("heldout/slither_heldout_scores.json")),
        ("Mythril 0.24.8", load_json("heldout/mythril_heldout_scores.json")),
    ]


def heldout_table() -> str:
    lines = [
        "\\begin{table*}[t]", "\\centering", "\\small",
        "\\caption{SolidiFI bug-injection benchmark (400 files: 350 with injected bugs, 50 clean), scored on reentrancy and arithmetic. v2 was run once under a protocol whose files were written before the run. v3 was run afterwards, on the engine revised with what the SmartBugs and SolidiFI results showed, so its row is post hoc. Denial of service has no injected class and is not scored.}",
        "\\label{tab:heldout}", "\\resizebox{\\textwidth}{!}{%", "\\begin{tabular}{@{}llrrrrlrl@{}}", "\\toprule",
        "Category & Tool & TP & FP & FN & TN & Recall (\\%) & Precision (\\%) & FPR (\\%) \\\\", "\\midrule",
    ]
    tools = heldout_tools()
    for index_category, (key, name) in enumerate(HELDOUT):
        for index, (tool, data) in enumerate(tools):
            lines.append(detection_line(name if index == 0 else "", tool, data["flagged_any"][key]))
        lines.append("\\midrule" if index_category == 0 else "\\bottomrule")
    lines += ["\\end{tabular}%", "}", "\\end{table*}", ""]
    return "\n".join(lines)


def ablation_table() -> str:
    summary = load_json("ablation/ablation_summary.json")
    full_fp = summary["full"]["reentrancy"]["fp"]
    lines = [
        "\\begin{table}[t]", "\\centering", "\\small",
        "\\caption{Component ablation of the reentrancy check (SWC-107) on SmartBugs-curated, 143 files. Each row changes one component of the final engine and keeps the rest. The last row reproduces the pre-fix engine. Recall and FPR use exact 95\\% Clopper--Pearson intervals.}",
        "\\label{tab:ablation}", "\\resizebox{\\columnwidth}{!}{%", "\\begin{tabular}{@{}lrrlrlr@{}}", "\\toprule",
        "Configuration & TP & FP & Recall (\\%) & Precision (\\%) & FPR (\\%) & $\\Delta$FP \\\\", "\\midrule",
    ]
    for key in ABLATIONS:
        s = summary[key]["reentrancy"]
        delta = s["fp"] - full_fp
        lines.append(f"{ABLATION_LABELS[key]} & {s['tp']} & {s['fp']} & "
                     f"{pct(s['recall'])}{interval(s['recall_ci95'])} & {pct(s['precision'])} & "
                     f"{pct(s['fpr'])}{interval(s['fpr_ci95'])} & {delta:+d} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}%", "}", "\\end{table}", ""]
    return "\n".join(lines)


def completed_only_table() -> str:
    evm_rows = load_rows("external/evm_guard_files.csv")
    lines = [
        "\\begin{table}[t]", "\\centering", "\\small",
        "\\caption{Sensitivity to baseline timeouts. Each baseline is scored only on the files it completed, and EVM-Guard v3 is scored on the same files. Recall and FPR use exact 95\\% Clopper--Pearson intervals.}",
        "\\label{tab:completed}", "\\resizebox{\\columnwidth}{!}{%", "\\begin{tabular}{@{}llrlrlr@{}}", "\\toprule",
        "Tool (files) & Category & Tool TP & Tool recall (\\%) & EVM-Guard TP & EVM-Guard recall (\\%) & EVM-Guard FPR (\\%) \\\\",
        "\\midrule",
    ]
    for tool, pattern in (("Slither", "external/slither_files_*.csv"), ("Mythril", "external/mythril_files_*.csv")):
        baseline = load_rows(pattern)
        completed = {row["contract_id"] for row in baseline if row["status"] == "ok"}
        tool_subset = [row for row in baseline if row["contract_id"] in completed]
        evm_subset = [row for row in evm_rows if row["contract_id"] in completed]
        for index, (key, name) in enumerate(SMARTBUGS[:3]):
            tool_score = score_category(tool_subset, key, "flagged_categories")
            evm_score = score_category(evm_subset, key, "flagged_categories")
            label = f"{tool} ({len(completed)})" if index == 0 else ""
            lines.append(f"{label} & {name} & {tool_score['tp']} & {pct(tool_score['recall'])} & "
                         f"{evm_score['tp']} & {pct(evm_score['recall'])}"
                         f"{interval(evm_score['recall_ci95'])} & {pct(evm_score['fpr'])} \\\\")
        lines.append("\\midrule" if tool == "Slither" else "\\bottomrule")
    lines += ["\\end{tabular}%", "}", "\\end{table}", ""]
    return "\n".join(lines)


def journal_tables() -> str:
    tools = smartbugs_tools(include_v2=True)
    return "".join([
        GENERATED_NOTE,
        detection_table(SMARTBUGS, tools,
                        "Per-category detection on SmartBugs-curated (143 files, 216 runtime contracts). EVM-Guard v1 is the engine frozen before the run. v2 is the revised engine, run after v1's results were known. v3 is the final engine, which adds the stipend, mutex and PUSH0 rules revised after the SmartBugs and SolidiFI results. v2 and v3 are post hoc. A tool with no mapped detector for a category flags nothing in it.",
                        "tab:detection", wide=True),
        runtime_table(), replay_counts_table(), replay_scores_table(), heldout_table(), ablation_table(),
        completed_only_table(),
    ])


def conference_tables() -> str:
    tools = smartbugs_tools(include_v2=False)
    return "".join([
        GENERATED_NOTE,
        detection_table(SMARTBUGS, tools,
                        "Detection on SmartBugs-curated (143 files, 216 runtime contracts). v1 was frozen before the run; v3 is the final engine, revised after the v2 results were known (post hoc).",
                        "tab:smartbugs_detection", wide=True),
        runtime_table(), replay_counts_table(), ablation_table(), completed_only_table(), heldout_table(),
    ])


def main() -> None:
    with open(os.path.join(PAPER, "rewrite", "generated_tables.tex"), "w", encoding="utf-8") as handle:
        handle.write(journal_tables())
    with open(os.path.join(PAPER, "rewrite", "generated_tables_conference.tex"), "w", encoding="utf-8") as handle:
        handle.write(conference_tables())
    print("wrote paper/rewrite/generated_tables.tex and paper/rewrite/generated_tables_conference.tex")


if __name__ == "__main__":
    main()
